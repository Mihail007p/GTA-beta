import { chromium } from 'playwright';
const browser = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const page = await (await browser.newContext({ viewport: { width: 820, height: 370 } })).newPage();
await page.goto('http://localhost:8080/?shot&noaudio');
await page.waitForFunction(() => window.__game && window.__game.state === 'menu', null, { timeout: 60000 });
const progs = () => page.evaluate(() => window.__game.R.renderer.info.programs.map(p => p.name + ':' + p.id));
const a = await progs();
await page.click('#btn-play');
await page.keyboard.down('ArrowUp'); await new Promise(r => setTimeout(r, 5000));
const b = await progs();
await page.keyboard.down('ArrowRight'); await page.keyboard.down('Space'); await new Promise(r => setTimeout(r, 3000));
await page.keyboard.up('Space'); await page.keyboard.up('ArrowRight');
await new Promise(r => setTimeout(r, 2000));
const c = await progs();
const st = await page.evaluate(() => ({ skids: window.__game.R.skidCount ?? null, drift: window.__game.car.stats.maxDrift ?? null, kmh: Math.round(Math.abs(window.__game.car.speed) * 3.6) }));
console.log('программ в меню:', a.length, '| после старта:', b.length, '| после заноса:', c.length, JSON.stringify(st));
const nb = b.filter(x => !a.includes(x)), nc = c.filter(x => !b.includes(x));
console.log('новые при старте:', nb.join(', ') || '—');
console.log('новые при заносе:', nc.join(', ') || '—');
await browser.close();
